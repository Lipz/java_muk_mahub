-- ============================================================
-- 9. RETENTION
--
--   server_resources         1 day   -- 3-5s scrapes; volume is the constraint
--   server_storage           30 days -- hourly scrapes; capacity trending
--   server_storage_summary   30 days
--
-- drop_chunks is a metadata operation, so this costs nothing compared
-- to a nightly DELETE churning dead tuples.
--
-- Removed and re-added rather than add(if_not_exists => TRUE), because
-- that form leaves an EXISTING policy untouched -- re-running this file
-- would not apply a changed interval. Remove-then-add makes the value
-- declared here authoritative.
--
-- Compression is still NOT enabled. Even at 30 days the storage tables
-- hold on the order of 14k rows; columnar compression is worth its
-- complexity at a far larger scale, or alongside continuous aggregates
-- retained longer than the raw data.
-- ============================================================

SELECT remove_retention_policy('server_resources',       if_exists => TRUE);
SELECT remove_retention_policy('server_storage',         if_exists => TRUE);
SELECT remove_retention_policy('server_storage_summary', if_exists => TRUE);

SELECT add_retention_policy('server_resources',       INTERVAL '1 day');
SELECT add_retention_policy('server_storage',         INTERVAL '30 days');
SELECT add_retention_policy('server_storage_summary', INTERVAL '30 days');


